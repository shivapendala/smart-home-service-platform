class InventoryMasterEntityBase(BaseModel):
    entity_code: str = Field(..., max_length=100)
    name: str = Field(..., max_length=200)
    description: Optional[str] = None
    status: InventoryStatus = InventoryStatus.ACTIVE
    priority: InventoryPriority = InventoryPriority.NORMAL
    category_type: InventoryCategoryType = InventoryCategoryType.PRIMARY
    amount: float = Field(0.0, ge=0.0)
    quantity: int = Field(1, ge=1)
    score: float = 100.0
    is_active: bool = True
    is_flagged: bool = False

class InventoryMasterEntityCreate(InventoryMasterEntityBase):
    pass

class InventoryMasterEntityUpdate(BaseModel):
    name: Optional[str] = None
    description: Optional[str] = None
    status: Optional[InventoryStatus] = None
    priority: Optional[InventoryPriority] = None
    amount: Optional[float] = None
    quantity: Optional[int] = None
    is_active: Optional[bool] = None

class InventoryMasterEntityResponse(InventoryMasterEntityBase):
    id: int
    user_id: Optional[int] = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)

